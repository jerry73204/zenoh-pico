uint32_t _z_crc32(const uint8_t *message, size_t len) {
    uint32_t crc = 0xFFFFFFFF;
    for (size_t i = 0; i < len; i++) {
        crc = (crc >> 8) ^ _z_crc32_table[(crc ^ (uint32_t)message[i]) & 0xFFu];
    }
    return ~crc;
}
